// Regenerate hermes/services/tlds.ts from the IANA root zone TLD list.
// Usage: npm run update-tlds
// Exits 0 and leaves the file untouched when IANA's version is unchanged.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt";
const TARGET = fileURLToPath(
  new URL("../hermes/services/tlds.ts", import.meta.url)
);

const res = await fetch(SOURCE);
if (!res.ok) {
  console.error(`IANA fetch failed: HTTP ${res.status}`);
  process.exit(1);
}
const body = await res.text();
const lines = body.split(/\r?\n/);
const version = lines[0].replace(/^#\s*/, "");

// Sanity check: refuse to write a truncated or unexpected file.
const tlds = lines
  .filter((l) => l && !l.startsWith("#") && !l.startsWith("XN--"))
  .map((l) => l.trim().toLowerCase());
if (!version.startsWith("Version") || tlds.length < 1000) {
  console.error(`Unexpected IANA response (${tlds.length} TLDs), not writing.`);
  process.exit(1);
}

const current = await readFile(TARGET, "utf8").catch(() => "");
if (current.includes(`// ${version}`)) {
  console.log(`tlds.ts already at ${version}`);
  process.exit(0);
}

// Wrap the space-separated list at ~72 columns as string concatenation.
const rows = [];
let row = "";
for (const tld of tlds) {
  if (row && row.length + tld.length + 1 > 70) {
    rows.push(row + " ");
    row = "";
  }
  row += (row ? " " : "") + tld;
}
rows.push(row);

const out = `// IANA root zone TLDs, ASCII only (IDN xn-- entries dropped: the domain
// pattern in ioc-extractor.ts only matches ASCII TLDs).
// Source: ${SOURCE}
// ${version}
// Generated by scripts/update-tlds.mjs (npm run update-tlds). Do not edit.

const RAW =
${rows.map((r) => `  ${JSON.stringify(r)}`).join(" +\n")};

export const IANA_TLDS: ReadonlySet<string> = new Set(RAW.split(/\\s+/));
`;

await writeFile(TARGET, out);
console.log(`tlds.ts updated: ${tlds.length} TLDs, ${version}`);
